#!/usr/bin/env python3
"""Builds native/runtime/kernel/font8x16.h: the 8x16 bitmap font the Vanta kernel draws framebuffer text with.

Letters come from DejaVu Sans Mono (Bitstream Vera license: free to use and redistribute), rendered at 8x16 and
thresholded; box-drawing and block characters are drawn exactly by this script so lines join up across cells.
Run it again only to change the font:  python3 tools/make_kernel_font.py [path/to/DejaVuSansMono.ttf]
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "native", "runtime", "kernel", "font8x16.h")

# Extra glyphs (Unicode -> slot 128+) shared with the VGA text console, which maps them to code page 437.
EXTRA = ["█", "░", "▒", "▓", "▀", "▄", "─", "│", "┌", "┐", "└", "┘", "├", "┤", "┬", "┴", "┼",
         "═", "║", "╔", "╗", "╚", "╝", "•", "·", "°", "←", "↑", "→", "↓", "♥", "★", "■", "▲", "▼", "◆"]
CP437 = {"█": 219, "░": 176, "▒": 177, "▓": 178, "▀": 223, "▄": 220, "─": 196, "│": 179, "┌": 218, "┐": 191,
         "└": 192, "┘": 217, "├": 195, "┤": 180, "┬": 194, "┴": 193, "┼": 197, "═": 205, "║": 186, "╔": 201,
         "╗": 187, "╚": 200, "╝": 188, "•": 7, "·": 250, "°": 248, "←": 27, "↑": 24, "→": 26, "↓": 25,
         "♥": 3, "★": 15, "■": 254, "▲": 30, "▼": 31, "◆": 4}


def find_font():
    if len(sys.argv) > 1 and sys.argv[1]:
        return sys.argv[1]
    try:
        import matplotlib
        p = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSansMono.ttf")
        if os.path.exists(p):
            return p
    except ImportError:
        pass
    sys.exit("give the path to DejaVuSansMono.ttf")


def box(ch):
    """Exact 8x16 bitmaps for line and block characters."""
    g = [[0] * 8 for _ in range(16)]
    def hline(y, x0=0, x1=8):
        for x in range(x0, x1): g[y][x] = 1
    def vline(x, y0=0, y1=16):
        for y in range(y0, y1): g[y][x] = 1
    L = {"─": "lr", "│": "ud", "┌": "rd", "┐": "ld", "└": "ru", "┘": "lu", "├": "udr", "┤": "udl",
         "┬": "lrd", "┴": "lru", "┼": "udlr"}
    D = {"═": "lr", "║": "ud", "╔": "rd", "╗": "ld", "╚": "ru", "╝": "lu"}
    if ch in L:
        s = L[ch]
        if "l" in s: hline(7, 0, 4)
        if "r" in s: hline(7, 3, 8)
        if "u" in s: vline(3, 0, 8)
        if "d" in s: vline(3, 7, 16)
        return g
    if ch in D:
        s = D[ch]
        for off in (0, 1):
            y, x = 6 + off * 2, 2 + off * 2
            # double lines: outer and inner strokes
        if s == "lr": hline(6); hline(9)
        elif s == "ud": vline(2); vline(5)
        elif s == "rd": hline(6, 2, 8); vline(2, 6, 16); hline(9, 5, 8); vline(5, 9, 16)
        elif s == "ld": hline(6, 0, 6); vline(5, 6, 16); hline(9, 0, 3); vline(2, 9, 16)
        elif s == "ru": hline(9, 2, 8); vline(2, 0, 10); hline(6, 5, 8); vline(5, 0, 7)
        elif s == "lu": hline(9, 0, 6); vline(5, 0, 10); hline(6, 0, 3); vline(2, 0, 7)
        return g
    if ch == "█": return [[1] * 8 for _ in range(16)]
    if ch == "▀": return [[1] * 8 if y < 8 else [0] * 8 for y in range(16)]
    if ch == "▄": return [[1] * 8 if y >= 8 else [0] * 8 for y in range(16)]
    if ch == "░": return [[1 if (x + y * 2) % 4 == 0 else 0 for x in range(8)] for y in range(16)]
    if ch == "▒": return [[1 if (x + y) % 2 == 0 else 0 for x in range(8)] for y in range(16)]
    if ch == "▓": return [[0 if (x + y * 2) % 4 == 0 else 1 for x in range(8)] for y in range(16)]
    if ch == "■":
        for y in range(4, 12):
            for x in range(1, 7): g[y][x] = 1
        return g
    return None


def render(font, ch):
    b = box(ch)
    if b is not None:
        return b
    img = Image.new("L", (8, 16), 0)
    d = ImageDraw.Draw(img)
    w = d.textlength(ch, font=font)
    d.text(((8 - w) / 2, 0), ch, font=font, fill=255)
    return [[1 if img.getpixel((x, y)) >= 110 else 0 for x in range(8)] for y in range(16)]


def main():
    font = ImageFont.truetype(find_font(), 13)
    glyphs = [render(font, chr(c)) for c in range(32, 127)] + [render(font, ch) for ch in EXTRA]
    rows = []
    for g in glyphs:
        rows.append(", ".join("0x%02x" % sum(bit << (7 - x) for x, bit in enumerate(r)) for r in g))
    with open(OUT, "w") as f:
        f.write("/* 8x16 bitmap font for the Vanta kernel's framebuffer text. Generated by tools/make_kernel_font.py\n"
                " * from DejaVu Sans Mono (Bitstream Vera license) plus exact box-drawing glyphs. Do not edit. */\n")
        f.write("#define KFONT_FIRST 32\n#define KFONT_ASCII 95\n#define KFONT_EXTRA %d\n" % len(EXTRA))
        f.write("static const unsigned char kfont[%d][16] = {\n" % len(glyphs))
        for i, r in enumerate(rows):
            label = chr(32 + i) if i < 95 else EXTRA[i - 95]
            f.write("    {%s}, /* %s */\n" % (r, "U+%04X" % ord(label) if label in "*/\\" or ord(label) > 126 else label))
        f.write("};\n")
        f.write("/* the extra glyphs: Unicode code point, slot in kfont, code page 437 character for VGA text mode */\n")
        f.write("static const struct { unsigned cp; unsigned char slot, cp437; } kfont_extra[] = {\n")
        for i, ch in enumerate(EXTRA):
            f.write("    {0x%04X, %d, %d},\n" % (ord(ch), 95 + i, CP437[ch]))
        f.write("};\n")
    # a preview to look at
    prev = Image.new("L", (16 * 9, ((len(glyphs) + 15) // 16) * 17), 40)
    for i, g in enumerate(glyphs):
        ox, oy = (i % 16) * 9, (i // 16) * 17
        for y in range(16):
            for x in range(8):
                if g[y][x]: prev.putpixel((ox + x, oy + y), 255)
    prev = prev.resize((prev.width * 4, prev.height * 4), Image.NEAREST)
    if len(sys.argv) > 2:
        prev.save(sys.argv[2])
    print("wrote", OUT)


if __name__ == "__main__":
    main()
